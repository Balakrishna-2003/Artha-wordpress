<script>
(function () {
  'use strict';

  /* ============ ROBUST SCROLL REVEAL ============ */
  const animElements = document.querySelectorAll('.anim-base');
  if ('IntersectionObserver' in window) {
    const io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (e.isIntersecting) {
          e.target.classList.add('anim-is-visible');
          io.unobserve(e.target);
        }
      });
    }, { threshold: 0.15, rootMargin: '0px 0px -50px 0px' });
    animElements.forEach(function (el) { io.observe(el); });
  } else {
    animElements.forEach(function (el) { el.classList.add('anim-is-visible'); });
  }

  /* ============ HOTEL JOB APPLICATION FORM ============ */
  const form = document.getElementById('hotelJobApplicationForm');
  const cvInput = document.getElementById('app-cv');
  const cvFilename = document.getElementById('app-cv-filename');
  const uploadBox = cvInput ? cvInput.closest('.app-upload-box') : null;
  const uploadIcon = uploadBox ? uploadBox.querySelector('.app-upload-ic i') : null;
  const roleInput = document.getElementById('app-role');
  const statusEl = document.getElementById('app-form-status');
  const allowedExt = /\.(pdf|doc|docx)$/i;

  document.querySelectorAll('.job-apply-btn[data-job-role]').forEach(function (btn) {
    btn.addEventListener('click', function () {
      if (roleInput && btn.dataset.jobRole) {
        roleInput.value = btn.dataset.jobRole;
      }
    });
  });

  if (cvInput && cvFilename) {
    cvInput.addEventListener('change', function () {
      const file = cvInput.files && cvInput.files[0];
      if (!file) {
        cvFilename.textContent = 'Choose a file to upload';
        if (uploadIcon) uploadIcon.className = 'fas fa-cloud-arrow-up';
        return;
      }
      if (!allowedExt.test(file.name)) {
        cvInput.value = '';
        cvFilename.textContent = 'Choose a file to upload';
        if (uploadIcon) uploadIcon.className = 'fas fa-cloud-arrow-up';
        if (statusEl) {
          statusEl.className = 'app-form-status error';
          statusEl.textContent = 'Please upload a valid CV/Resume file (.pdf, .doc, or .docx).';
        }
        return;
      }
      if (statusEl) {
        statusEl.className = 'app-form-status';
        statusEl.textContent = '';
      }
      cvFilename.textContent = 'Chosen file: ' + file.name;
      if (uploadIcon) uploadIcon.className = 'fas fa-file-circle-check';
    });
  }

  if (form && statusEl) {
    form.addEventListener('submit', function (e) {
      e.preventDefault();
      const name = document.getElementById('app-name').value.trim();
      const phone = document.getElementById('app-phone').value.trim();
      const emailEl = document.getElementById('app-email');
      const email = emailEl ? emailEl.value.trim() : '';
      const city = document.getElementById('app-city').value;
      const role = roleInput ? roleInput.value.trim() : '';
      const exp = document.getElementById('app-exp').value;
      const file = cvInput && cvInput.files && cvInput.files[0];

      if (!name || !phone || !email || !city || !role || !exp) {
        statusEl.className = 'app-form-status error';
        statusEl.textContent = 'Please fill in all required fields (Full Name, Phone / WhatsApp Number, Email Address, City, Job Role, and Experience).';
        return;
      }
      if (!/^[0-9+\-\s()]{7,20}$/.test(phone)) {
        statusEl.className = 'app-form-status error';
        statusEl.textContent = 'Please enter a valid Phone / WhatsApp Number.';
        return;
      }
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
        statusEl.className = 'app-form-status error';
        statusEl.textContent = 'Please enter a valid Email Address.';
        return;
      }
      if (file && !allowedExt.test(file.name)) {
        statusEl.className = 'app-form-status error';
        statusEl.textContent = 'Please upload a valid CV/Resume file (.pdf, .doc, or .docx).';
        return;
      }

      statusEl.className = 'app-form-status info';
      statusEl.textContent = 'Details validated and ready. Connect a backend form endpoint to receive submissions, or click "Apply via WhatsApp" below to send your details directly.';
    });
  }

  /* ============ JOB OPPORTUNITIES PAGINATION ============ */
  (function () {
    const CARDS_PER_PAGE = 9;
    const jobsSection = document.getElementById('job-opportunities');
    if (!jobsSection) return;

    const jobsGrid = jobsSection.querySelector('.jobs-grid');
    const paginationEl = jobsSection.querySelector('.jobs-pagination') || document.getElementById('jobsPagination');
    if (!jobsGrid || !paginationEl) return;

    const cards = Array.from(jobsGrid.querySelectorAll('.job-card'));
    if (cards.length <= CARDS_PER_PAGE) {
      paginationEl.hidden = true;
      return;
    }

    const totalPages = Math.ceil(cards.length / CARDS_PER_PAGE);
    let currentPage = 1;

    function renderPage(page, shouldScroll) {
      currentPage = Math.max(1, Math.min(page, totalPages));
      const startIdx = (currentPage - 1) * CARDS_PER_PAGE;
      const endIdx = startIdx + CARDS_PER_PAGE;

      cards.forEach(function (card, index) {
        const isVisible = index >= startIdx && index < endIdx;
        card.classList.toggle('is-hidden-page', !isVisible);
        if (isVisible) card.classList.add('anim-is-visible');
      });

      paginationEl.hidden = false;
      paginationEl.innerHTML = '';

      const prevBtn = document.createElement('button');
      prevBtn.type = 'button';
      prevBtn.className = 'jobs-page-btn prev';
      prevBtn.disabled = currentPage === 1;
      prevBtn.setAttribute('aria-label', 'Previous page');
      prevBtn.innerHTML = '<i class="fas fa-chevron-left" aria-hidden="true"></i> Prev';
      prevBtn.addEventListener('click', function () { renderPage(currentPage - 1, true); });
      paginationEl.appendChild(prevBtn);

      for (let i = 1; i <= totalPages; i++) {
        const pageBtn = document.createElement('button');
        pageBtn.type = 'button';
        pageBtn.className = 'jobs-page-btn num' + (i === currentPage ? ' active' : '');
        pageBtn.textContent = i;
        pageBtn.setAttribute('aria-label', 'Page ' + i);
        if (i === currentPage) pageBtn.setAttribute('aria-current', 'page');
        (function (targetPage) {
          pageBtn.addEventListener('click', function () {
            if (targetPage !== currentPage) renderPage(targetPage, true);
          });
        })(i);
        paginationEl.appendChild(pageBtn);
      }

      const nextBtn = document.createElement('button');
      nextBtn.type = 'button';
      nextBtn.className = 'jobs-page-btn next';
      nextBtn.disabled = currentPage === totalPages;
      nextBtn.setAttribute('aria-label', 'Next page');
      nextBtn.innerHTML = 'Next <i class="fas fa-chevron-right" aria-hidden="true"></i>';
      nextBtn.addEventListener('click', function () { renderPage(currentPage + 1, true); });
      paginationEl.appendChild(nextBtn);

      if (shouldScroll) {
        jobsSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    }

    renderPage(1, false);
  })();

})();
</script>

